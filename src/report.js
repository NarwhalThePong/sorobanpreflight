'use strict';
const { rules } = require('./rules');
const { PRIORITY_ORDER } = require('./scan');
function toMarkdown(res) {
  const L = ['# Soroban pre-audit self-review report', '', `Generated by sorobanpreflight ${res.version}. Scanned ${res.filesScanned.length} Rust file(s).`, '',
    '> This is a checklist aid for self-review before an audit. It is not an audit and gives no security guarantee. Hits are pattern matches that need human review; some will be false positives, and many real issues will not be detected.', ''];
  const counts = { high: 0, medium: 0, low: 0, info: 0 }; const byId = Object.fromEntries(rules.map(r => [r.id, r]));
  for (const f of res.findings) counts[f.priority || byId[f.rule].priority]++;
  L.push('## Summary', '', '| Review priority | Hits |', '|---|---|', ...['high', 'medium', 'low', 'info'].map(p => `| ${p} | ${counts[p]} |`));
  if (res.readiness) L.push('', `Pre-audit readiness: **${res.readiness.score}/${res.readiness.total}** items present.`);
  L.push('', '## Checklist', '');
  for (const cat of [...new Set(rules.map(r => r.category))]) {
    L.push(`### ${cat}`, '');
    for (const r of rules.filter(r => r.category === cat).sort((a, b) => PRIORITY_ORDER[a.priority] - PRIORITY_ORDER[b.priority])) {
      const hits = res.findings.filter(f => f.rule === r.id);
      L.push(`- [${hits.length ? ' ' : 'x'}] **${r.id}** ${r.title} — _${r.priority} review priority_ — ${hits.length ? hits.length + ' hit(s)' : 'no hits'}`);
      if (hits.length) { L.push(`  - Why it matters: ${r.why}`, `  - How to verify: ${r.verify}`); for (const h of hits.slice(0, 25)) L.push(`  - \`${h.file}:${h.line}\` — ${h.note.replace(/`/g, "'")}${h.priority && h.priority !== r.priority ? ` _(${h.priority})_` : ''}`); if (hits.length > 25) L.push(`  - …and ${hits.length - 25} more (see --json)`); }
    }
    L.push('');
  }
  if (res.readiness) { L.push('## Pre-audit readiness', '', '| ID | Item | Status | Detail |', '|---|---|---|---|'); for (const i of res.readiness.items) L.push(`| ${i.id} | ${i.item} | ${i.ok ? 'yes' : 'no'} | ${String(i.detail).replace(/\|/g, '\\|')} |`); L.push(''); }
  return L.join('\n');
}
const toJSON = res => JSON.stringify(res, null, 2);
module.exports = { toMarkdown, toJSON };
